/// The state owner: authoritative storage and the services the API tier calls. It has no network
/// listener. Every call arrives from the API tier with this process's internal credential and
/// names the principal the API tier authenticated.
#[derive(Clone)]
pub struct ControlPlane {
    store: Store,
    internal_token: Arc<String>,
    /// The admin operator, whose Inbox the Gateways' operator notifications report.
    admin_operator: Arc<String>,
}

impl ControlPlane {
    /// `internal_token` is generated by the process for its API tier; `admin_operator` is the
    /// admin operator's principal, such as `operator:local`.
    pub async fn open(
        database_url: &str,
        internal_token: String,
        admin_operator: String,
    ) -> anyhow::Result<Self> {
        anyhow::ensure!(
            !internal_token.is_empty(),
            "an internal API tier credential is required"
        );
        anyhow::ensure!(
            admin_operator
                .strip_prefix("operator:")
                .is_some_and(|id| !id.is_empty() && !id.starts_with("token:")),
            "the admin operator principal must be operator:ID"
        );
        Ok(Self {
            store: Store::open(database_url).await?,
            internal_token: Arc::new(internal_token),
            admin_operator: Arc::new(admin_operator),
        })
    }

    /// Also writes every committed audit entry to `sink`.
    pub fn with_audit_sink(mut self, sink: crate::AuditSink) -> Self {
        self.store = self.store.with_audit_sink(sink);
        self
    }

    /// Records the deployment's default thread for Objective notices, or clears it, and returns
    /// the value it replaced, which another replica may have recorded.
    pub async fn set_default_notification_task(
        &self,
        task_id: Option<&str>,
    ) -> anyhow::Result<Option<String>> {
        Ok(self.store.set_default_notification_task(task_id).await?)
    }

    /// Records a credential from the Control Plane's startup configuration, such as the
    /// bootstrap `host:local` or `gateway:local`.
    pub async fn seed_enrollment(
        &self,
        role: Role,
        name: &str,
        token_digest: &[u8],
    ) -> anyhow::Result<()> {
        self.store.seed_enrollment(role, name, token_digest).await?;
        Ok(())
    }

    fn host_authority<T>(&self, request: &Request<T>) -> Result<HostAuthority, Status> {
        let principal = self.principal(request, "host:")?;
        Ok(HostAuthority::new(principal, host_generation(request)?)?)
    }

    /// Runs the periodic maintenance pass when this replica claims the current tick. Replicas
    /// sharing one database run one pass per `interval` between them.
    pub async fn maintain(&self, interval: std::time::Duration) -> anyhow::Result<bool> {
        if !self.store.claim_maintenance(interval).await? {
            return Ok(false);
        }
        self.sweep().await?;
        Ok(true)
    }

    pub async fn sweep(&self) -> anyhow::Result<()> {
        self.store.sweep_objectives().await?;
        self.store.sweep_expired_attempts().await?;
        self.store.sweep_inputs().await?;
        self.store.sweep_artifact_transfer_grants().await?;
        self.store.sweep_mailbox().await?;
        self.store.sweep_approvals().await?;
        self.store.sweep_work_sessions().await?;
        self.store.sweep_commit_reviews().await?;
        self.store.sweep_replies().await?;
        self.store.sweep_github_publications().await?;
        self.store.sweep_ephemeral_hosts().await?;
        self.store.prune_watch().await?;
        Ok(())
    }

    fn principal<T>(&self, request: &Request<T>, class: &str) -> Result<String, Status> {
        let principal = internal_principal(request, &self.internal_token)?;
        let Some(identity) = principal.strip_prefix(class) else {
            return Err(Status::permission_denied(
                "caller is not allowed to use this service",
            ));
        };
        if identity.is_empty() || principal.len() > 256 {
            return Err(Status::permission_denied("invalid caller identity"));
        }
        Ok(principal.to_owned())
    }

    /// An operator or a client: the principals that converse and own work.
    fn actor<T>(&self, request: &Request<T>) -> Result<String, Status> {
        let principal = internal_principal(request, &self.internal_token)?;
        if !(principal.starts_with("operator:") || principal.starts_with("client:"))
            || principal.len() > 256
        {
            return Err(Status::permission_denied(
                "caller is not allowed to use this service",
            ));
        }
        Ok(principal.to_owned())
    }

    /// A Gateway call for one connector account: the internal `connector:ACCOUNT` principal, once
    /// the account is bound to the calling Gateway.
    async fn connector<T>(&self, request: &Request<T>) -> Result<String, Status> {
        let gateway = self.principal(request, "gateway:")?;
        let account = request
            .metadata()
            .get(CONNECTOR_ACCOUNT_HEADER)
            .and_then(|value| value.to_str().ok())
            .filter(|value| !value.is_empty() && value.len() <= 200)
            .ok_or_else(|| Status::invalid_argument("connector account required"))?;
        self.store
            .bind_connector_account(&gateway["gateway:".len()..], account)
            .await?;
        Ok(format!("connector:{account}"))
    }
}

impl From<StoreError> for Status {
    fn from(error: StoreError) -> Self {
        match error {
            StoreError::InvalidArgument(message) => Self::invalid_argument(message),
            StoreError::NotFound(message) => Self::not_found(message),
            StoreError::Conflict(message) => Self::already_exists(message),
            StoreError::FailedPrecondition(message) => Self::failed_precondition(message),
            StoreError::PermissionDenied => {
                Self::permission_denied("execution ownership does not match")
            }
            StoreError::Storage(_) | StoreError::Data(_) => {
                Self::internal("storage operation failed")
            }
        }
    }
}

