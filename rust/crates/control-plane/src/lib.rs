#[cfg(test)]
mod tests {
    use super::*;
    use supertag_protocol::{
        authenticated_request, v2::connector_server::Connector, v2::operator_server::Operator,
        v2::worker_host_server::WorkerHost,
    };

    #[tokio::test]
    async fn private_api_requires_gateway_and_preserves_principal_class() {
        let cp = ControlPlane::open(
            "sqlite::memory:",
            "private-key".into(),
            "operator:local".into(),
        )
        .await
        .unwrap();
        let tag = PutTagRequest {
            name: None,
            expected_revision: None,
            execution: None,
            approval_rules: vec![],
            harness_kind: 0,
            workspace: None,
            tag_id: "tag".into(),
            instructions: String::new(),
            allowed_actions: vec![],
        };
        assert_eq!(
            cp.put_tag(Request::new(tag.clone()))
                .await
                .unwrap_err()
                .code(),
            tonic::Code::Unauthenticated
        );
        assert_eq!(
            cp.put_tag(
                authenticated_request(tag.clone(), "wrong", Some("operator:alice")).unwrap()
            )
            .await
            .unwrap_err()
            .code(),
            tonic::Code::Unauthenticated
        );
        assert_eq!(
            cp.put_tag(
                authenticated_request(tag.clone(), "private-key", Some("host:worker")).unwrap()
            )
            .await
            .unwrap_err()
            .code(),
            tonic::Code::PermissionDenied
        );
        assert_eq!(
            cp.put_tag(
                authenticated_request(tag.clone(), "private-key", Some("operator:")).unwrap()
            )
            .await
            .unwrap_err()
            .code(),
            tonic::Code::PermissionDenied
        );
        assert!(
            cp.put_tag(authenticated_request(tag, "private-key", Some("operator:alice")).unwrap())
                .await
                .is_ok()
        );
        let claim = ClaimTaskRequest {
            harness_kind: 0,
            workspace_ids: vec![],
            operation_id: "claim".into(),
            context_contracts: vec![],
            execution_profile: None,
            gateway_workspace_ids: vec![],
        };
        assert_eq!(
            cp.claim_task(
                authenticated_request(claim, "private-key", Some("operator:alice")).unwrap()
            )
            .await
            .unwrap_err()
            .code(),
            tonic::Code::PermissionDenied
        );
        assert_eq!(
            cp.claim_reply(
                authenticated_request(
                    ClaimReplyRequest {
                        operation_id: "delivery".into(),
                        connector_lease_token: String::new(),
                    },
                    "private-key",
                    Some("operator:alice")
                )
                .unwrap()
            )
            .await
            .unwrap_err()
            .code(),
            tonic::Code::PermissionDenied
        );
        let event = AcceptEventRequest {
            requested_execution: None,
            account_id: "account-a".into(),
            event_id: "event".into(),
            tag_id: "tag".into(),
            session_id: "session".into(),
            prompt: "hello".into(),
            destination: Some(ReplyDestination {
                conversation_id: "room".into(),
                thread_id: None,
            }),
        };
        // A connector call names its account; only a Gateway may make one.
        for (principal, code) in [
            ("operator:alice", tonic::Code::PermissionDenied),
            ("client:laptop", tonic::Code::PermissionDenied),
        ] {
            let mut request =
                authenticated_request(event.clone(), "private-key", Some(principal)).unwrap();
            request
                .metadata_mut()
                .insert(CONNECTOR_ACCOUNT_HEADER, "account-b".parse().unwrap());
            assert_eq!(cp.accept_event(request).await.unwrap_err().code(), code);
        }
        let mut missing =
            authenticated_request(event.clone(), "private-key", Some("gateway:edge")).unwrap();
        missing.metadata_mut().remove(CONNECTOR_ACCOUNT_HEADER);
        assert_eq!(
            cp.accept_event(missing).await.unwrap_err().code(),
            tonic::Code::InvalidArgument
        );
    }

    /// Accounts no Surface Account names admit work on any Tag, and the admin operator's
    /// notifications span every Tag, so only a Gateway whose Auth Key trusts it with every Tag
    /// serves them. A Gateway enrolled without it is refused both.
    #[tokio::test]
    async fn only_a_gateway_trusted_with_every_tag_serves_unnamed_accounts_and_notifications() {
        use sha2::{Digest, Sha256};
        use supertag_protocol::v2::operator_notifications_server::OperatorNotifications;
        let cp = ControlPlane::open(
            "sqlite::memory:",
            "private-key".into(),
            "operator:local".into(),
        )
        .await
        .unwrap();
        cp.seed_enrollment(Role::Gateway, "local", &Sha256::digest(b"local gateway"))
            .await
            .unwrap();
        let key = Sha256::digest(b"narrow gateway key").to_vec();
        cp.store
            .create_auth_key(
                "operator:local",
                &CreateAuthKeyRequest {
                    name: "narrow".into(),
                    role: PrincipalRole::Gateway.into(),
                    operation_id: "narrow-key".into(),
                    key_digest: key.clone(),
                    ..Default::default()
                },
            )
            .await
            .unwrap();
        cp.store
            .enroll(
                &key,
                &EnrollRequest {
                    role: PrincipalRole::Gateway.into(),
                    name: "narrow".into(),
                    operation_id: "narrow-enroll".into(),
                    token_digest: Sha256::digest(b"narrow credential").to_vec(),
                },
            )
            .await
            .unwrap();
        // No Auth Key enrolls a host or Gateway as `local`, the name the Control Plane seeds.
        let squat = Sha256::digest(b"squatting gateway key").to_vec();
        cp.store
            .create_auth_key(
                "operator:local",
                &CreateAuthKeyRequest {
                    name: "squat".into(),
                    role: PrincipalRole::Gateway.into(),
                    operation_id: "squat-key".into(),
                    key_digest: squat.clone(),
                    all_tags: true,
                    ..Default::default()
                },
            )
            .await
            .unwrap();
        assert!(matches!(
            cp.store
                .enroll(
                    &squat,
                    &EnrollRequest {
                        role: PrincipalRole::Gateway.into(),
                        name: "local".into(),
                        operation_id: "squat-enroll".into(),
                        token_digest: Sha256::digest(b"squat credential").to_vec(),
                    },
                )
                .await,
            Err(StoreError::InvalidArgument(_))
        ));
        for (gateway, admitted) in [
            ("gateway:local", true),
            ("gateway:narrow", false),
            ("gateway:unenrolled", false),
        ] {
            let claimed = cp
                .claim(
                    authenticated_request(
                        ClaimOperatorNotificationRequest::default(),
                        "private-key",
                        Some(gateway),
                    )
                    .unwrap(),
                )
                .await;
            assert_eq!(claimed.is_ok(), admitted, "{gateway} notifications");
            if !admitted {
                assert_eq!(claimed.unwrap_err().code(), tonic::Code::PermissionDenied);
            }
            let settled = cp
                .settle(
                    authenticated_request(
                        SettleOperatorNotificationRequest {
                            notification_id: "missing".into(),
                            lease_token: "lease".into(),
                            delivered: true,
                            ..Default::default()
                        },
                        "private-key",
                        Some(gateway),
                    )
                    .unwrap(),
                )
                .await
                .unwrap_err()
                .code();
            assert_eq!(
                settled,
                if admitted {
                    tonic::Code::NotFound
                } else {
                    tonic::Code::PermissionDenied
                },
                "{gateway} settle"
            );
            let mut request = authenticated_request(
                ClaimConnectorRequest {
                    owner_id: "owner".into(),
                },
                "private-key",
                Some(gateway),
            )
            .unwrap();
            request
                .metadata_mut()
                .insert(CONNECTOR_ACCOUNT_HEADER, "made-up-account".parse().unwrap());
            let leased = cp.claim_connector(request).await;
            assert_eq!(leased.is_ok(), admitted, "{gateway} unnamed account");
            if !admitted {
                assert_eq!(leased.unwrap_err().code(), tonic::Code::PermissionDenied);
            }
        }
    }
}
