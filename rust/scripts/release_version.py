"""Keep every released artifact on the Rust workspace version.

`workspace.package.version` in rust/Cargo.toml is the single source of truth for the SuperTag
version. The native archive, the supertag and supertag-tui binaries, the installer, the Python
SDK, the TypeScript SDK, every package.json, the desktop app, and the lockfiles must carry it.

    release_version.py --check        fail if any file drifts from rust/Cargo.toml
    release_version.py --sync         rewrite the drifting manifests to rust/Cargo.toml's version
    release_version.py v0.3.0-alpha.1 check, and also that the release tag names that version

Lockfiles are regenerated by their tools (cargo, uv) rather than rewritten here; --check still
reports them. Prints the version on success.
"""
import argparse
import json
import os
from pathlib import Path
import re
import sys
import tomllib

REPO = Path(__file__).resolve().parents[2]
VERSION = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?")
# Directories that never hold a tracked package.json.
SKIPPED_DIRECTORIES = {".git", "node_modules", "target", "dist", ".venv", ".turbo", ".pnpm-store"}
EMBEDDED_CLI = "packages/supertag-ai/src/cli.ts"
EMBEDDED_CLI_LINE = re.compile(r'^(process\.env\["SUPERTAG_CLI_VERSION"\] = ")([^"]*)(";)$', re.M)
TOML_VERSION = re.compile(r'^(version = ")([^"]*)(")$', re.M)
JSON_VERSION = re.compile(r'^(  "version": ")([^"]*)(",?)$', re.M)
# The desktop app depends on the Rust workspace crates by path, so its lockfile records them too.
CARGO_LOCKS = ["rust/Cargo.lock", "apps/desktop/src-tauri/Cargo.lock"]
WORKSPACE_CRATE = re.compile(r'^name = "(supertag-[a-z-]+)"\nversion = "([^"]*)"\n(?!source)', re.M)


def workspace_version(repo=REPO):
    version = tomllib.loads((repo / "rust/Cargo.toml").read_text())["workspace"]["package"]["version"]
    if not VERSION.fullmatch(version):
        raise ValueError(f"rust/Cargo.toml has an invalid release version {version!r}")
    return version


def python_version(version):
    """PEP 440 spells 0.3.0-alpha.1 as 0.3.0a1."""
    return re.sub(r"-(alpha|beta|rc)\.(\d+)$",
                  lambda m: {"alpha": "a", "beta": "b", "rc": "rc"}[m.group(1)] + m.group(2), version)


def tracked_files(repo, name):
    for directory, children, files in os.walk(repo):
        children[:] = sorted(c for c in children if c not in SKIPPED_DIRECTORIES)
        if name in files:
            yield Path(directory) / name


def manifests(repo):
    """(relative path, pattern) for each manifest that names the version on one line."""
    found = [(path.relative_to(repo).as_posix(), JSON_VERSION) for path in tracked_files(repo, "package.json")]
    found += [("sdks/python/pyproject.toml", TOML_VERSION),
              ("apps/desktop/src-tauri/Cargo.toml", TOML_VERSION),
              ("apps/desktop/src-tauri/tauri.conf.json", JSON_VERSION),
              (EMBEDDED_CLI, EMBEDDED_CLI_LINE)]
    return [(name, pattern) for name, pattern in found if (repo / name).exists()]


def drift(repo=REPO):
    """Every place that names another version than rust/Cargo.toml, as readable problems."""
    version = workspace_version(repo)
    problems = []
    for name, pattern in manifests(repo):
        match = pattern.search((repo / name).read_text())
        found = match.group(2) if match else None
        if found != version:
            problems.append(f"{name} is {found or 'unversioned'} but rust/Cargo.toml is {version}")
    for path in tracked_files(repo, "package-lock.json"):
        lock = json.loads(path.read_text())
        for found in {lock.get("version"), lock.get("packages", {}).get("", {}).get("version")}:
            if found is not None and found != version:
                problems.append(f"{path.relative_to(repo).as_posix()} records {found} but rust/Cargo.toml "
                                f"is {version}; run npm install --package-lock-only")
    uv_lock = repo / "sdks/python/uv.lock"
    if uv_lock.exists():
        match = re.search(r'^\[\[package\]\]\nname = "supertag"\nversion = "([^"]+)"', uv_lock.read_text(), re.M)
        if not match or match.group(1) != python_version(version):
            problems.append(f"sdks/python/uv.lock is {match.group(1) if match else 'unversioned'} "
                            f"but the Python SDK is {python_version(version)}; run uv lock")
    for name in CARGO_LOCKS:
        if not (repo / name).exists():
            continue
        for crate, found in WORKSPACE_CRATE.findall((repo / name).read_text()):
            if found != version:
                problems.append(f"{name} records {crate} {found} but rust/Cargo.toml is {version}; "
                                "run cargo metadata to refresh it")
    return problems


def sync(repo=REPO):
    """Rewrites each drifting manifest to the workspace version; returns the files it changed."""
    version = workspace_version(repo)
    changed = []
    for name, pattern in manifests(repo):
        path = repo / name
        text = path.read_text()
        updated = pattern.sub(lambda m: m.group(1) + version + m.group(3), text, count=1)
        if updated != text:
            path.write_text(updated)
            changed.append(name)
    return changed


def release_version(tag, repo=REPO):
    version = workspace_version(repo)
    if tag != f"v{version}":
        raise ValueError(f"release {tag} does not match the Rust workspace version {version}")
    problems = drift(repo)
    if problems:
        raise ValueError("; ".join(problems))
    return version


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("tag", nargs="?", help="release tag, for example v0.3.0-alpha.1")
    mode.add_argument("--check", action="store_true", help="fail if any file drifts from rust/Cargo.toml")
    mode.add_argument("--sync", action="store_true", help="rewrite drifting manifests to rust/Cargo.toml")
    args = parser.parse_args()
    try:
        if args.sync:
            for name in sync():
                print(f"updated {name}", file=sys.stderr)
            print(workspace_version())
        elif args.check:
            problems = drift()
            if problems:
                sys.exit("release version drift:\n  " + "\n  ".join(problems))
            print(workspace_version())
        else:
            print(release_version(args.tag))
    except (OSError, KeyError, ValueError) as error:
        sys.exit(f"release version: {error}")


if __name__ == "__main__":
    main()
