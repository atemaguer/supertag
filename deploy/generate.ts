import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { deploymentDefaults, DEPLOYMENT_RUNTIME as runtime } from "./shared/src/index.js";

const { parse, stringify } = createRequire(new URL("../apps/cli/package.json", import.meta.url))(
  "yaml",
) as {
  parse(source: string): unknown;
  stringify(value: unknown): string;
};
const root = new URL("../", import.meta.url);
const manifests: Record<string, unknown> = {
  "deploy/railway/railway.json": {
    $schema: "https://railway.com/railway.schema.json",
    build: { builder: "DOCKERFILE", dockerfilePath: "deploy/docker/Dockerfile" },
    deploy: {
      preDeployCommand: [runtime.migrationCommand],
      startCommand: runtime.startCommand,
      healthcheckPath: runtime.healthPath,
      healthcheckTimeout: 300,
      restartPolicyType: "ON_FAILURE",
      restartPolicyMaxRetries: 10,
    },
  },
};

// Fly's native format is TOML. Keep generated shared values in the same drift check.
const textManifests: Record<string, string> = {
  "deploy/fly/fly.toml": `# Generated by deploy/generate.ts. Select the app with --app and its region below.
primary_region = "iad"
kill_signal = "SIGTERM"
kill_timeout = "30s"

[build]
  dockerfile = "../docker/Dockerfile"

[deploy]
  release_command = ${JSON.stringify(runtime.migrationCommand)}
  strategy = "immediate"

[env]
${Object.entries(deploymentDefaults("fly"))
  .map(([key, value]) => `  ${key} = ${JSON.stringify(value)}`)
  .join("\n")}
  PORT = "${runtime.port}"

[[mounts]]
  source = "supertag_state"
  destination = ${JSON.stringify(runtime.stateDirectory)}

[http_service]
  internal_port = ${runtime.port}
  force_https = true
  auto_stop_machines = "off"
  auto_start_machines = true
  min_machines_running = 1

  [[http_service.checks]]
    interval = "15s"
    timeout = "5s"
    grace_period = "30s"
    method = "GET"
    path = ${JSON.stringify(runtime.healthPath)}

[[vm]]
  cpu_kind = "shared"
  cpus = 1
  memory = "1gb"
`,
};

// TLS passes through Fly Proxy unchanged. Certificates are operator-mounted, never generated.
textManifests["deploy/fly/fly.grpc.toml"] =
  textManifests["deploy/fly/fly.toml"]!.replace(
    'SUPERTAG_DEPLOYMENT_RPC_TRANSPORT = "websocket"',
    'SUPERTAG_DEPLOYMENT_RPC_TRANSPORT = "grpc"',
  ).replace(
    "[env]\n",
    `[env]\n  SUPERTAG_WORKLET_GRPC_PORT = "${runtime.grpcPort}"\n  SUPERTAG_WORKLET_GRPC_TLS_CERT_FILE = "/var/lib/supertag/tls/fullchain.pem"\n  SUPERTAG_WORKLET_GRPC_TLS_KEY_FILE = "/var/lib/supertag/tls/privkey.pem"\n`,
  ) +
  `
# Native TLS/HTTP2 passthrough; HTTP management remains on 443.
[[services]]
  protocol = "tcp"
  internal_port = ${runtime.grpcPort}
  auto_stop_machines = "off"
  auto_start_machines = true
  min_machines_running = 1

  [[services.ports]]
    port = 8443
    handlers = []
`;

const check = process.argv.includes("--check");
for (const [path, value] of Object.entries(manifests)) {
  const file = new URL(path, root);
  if (check) {
    const actual = parse(await readFile(file, "utf8"));
    if (JSON.stringify(actual) !== JSON.stringify(value))
      throw new Error(
        `${path} differs from the shared deployment configuration; run pnpm deploy:generate`,
      );
  } else {
    await mkdir(new URL(".", file), { recursive: true });
    await writeFile(
      file,
      path.endsWith(".json") ? `${JSON.stringify(value, null, 2)}\n` : stringify(value),
    );
  }
  process.stdout.write(`${check ? "Checked" : "Generated"} ${fileURLToPath(file)}\n`);
}
for (const [path, expected] of Object.entries(textManifests)) {
  const file = new URL(path, root);
  if (check) {
    if ((await readFile(file, "utf8")) !== expected)
      throw new Error(`${path} differs from shared configuration; run pnpm deploy:generate`);
  } else {
    await mkdir(new URL(".", file), { recursive: true });
    await writeFile(file, expected);
  }
  process.stdout.write(`${check ? "Checked" : "Generated"} ${fileURLToPath(file)}\n`);
}
