// TLS passes through Fly Proxy unchanged. Certificates are operator-mounted, never generated.
textManifests["deploy/fly/fly.grpc.toml"] =
  textManifests["deploy/fly/fly.toml"]!.replace(
    'SUPERTAG_DEPLOYMENT_RPC_TRANSPORT = "websocket"',
    'SUPERTAG_DEPLOYMENT_RPC_TRANSPORT = "grpc"',
  ).replace(
    "[env]\n",
    `[env]\n  SUPERTAG_WORKLET_GRPC_PORT = "${runtime.grpcPort}"\n  SUPERTAG_WORKLET_GRPC_TLS_CERT_FILE = "/var/lib/supertag/tls/fullchain.pem"\n  SUPERTAG_WORKLET_GRPC_TLS_KEY_FILE = "/var/lib/supertag/tls/privkey.pem"\n`,
  ) +
  `
# Native TLS/HTTP2 passthrough; HTTP management remains on 443.
[[services]]
  protocol = "tcp"
  internal_port = ${runtime.grpcPort}
  auto_stop_machines = "off"
  auto_start_machines = true
  min_machines_running = 1

  [[services.ports]]
    port = 8443
    handlers = []
`;

const check = process.argv.includes("--check");
for (const [path, value] of Object.entries(manifests)) {
  const file = new URL(path, root);
  if (check) {
    const actual = parse(await readFile(file, "utf8"));
    if (JSON.stringify(actual) !== JSON.stringify(value))
      throw new Error(
        `${path} differs from the shared deployment configuration; run pnpm deploy:generate`,
      );
  } else {
    await mkdir(new URL(".", file), { recursive: true });
    await writeFile(
      file,
      path.endsWith(".json") ? `${JSON.stringify(value, null, 2)}\n` : stringify(value),
    );
  }
  process.stdout.write(`${check ? "Checked" : "Generated"} ${fileURLToPath(file)}\n`);
}
for (const [path, expected] of Object.entries(textManifests)) {
  const file = new URL(path, root);
  if (check) {
    if ((await readFile(file, "utf8")) !== expected)
      throw new Error(`${path} differs from shared configuration; run pnpm deploy:generate`);
  } else {
    await mkdir(new URL(".", file), { recursive: true });
    await writeFile(file, expected);
  }
  process.stdout.write(`${check ? "Checked" : "Generated"} ${fileURLToPath(file)}\n`);
}
